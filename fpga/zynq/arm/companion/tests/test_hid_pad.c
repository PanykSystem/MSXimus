/* ejes con signo: X,Y int8 (-127..127), 4 botones */
static const unsigned char signed4[] = {
    0x05,0x01, 0x09,0x04, 0xA1,0x01,
    0x15,0x81, 0x25,0x7F, 0x75,0x08, 0x95,0x02, 0x09,0x30, 0x09,0x31, 0x81,0x02,
    0x05,0x09, 0x19,0x01, 0x29,0x04, 0x15,0x00, 0x25,0x01, 0x75,0x01, 0x95,0x04, 0x81,0x02,
    0x75,0x04, 0x95,0x01, 0x81,0x01,
    0xC0 };

static int fails;
static void check(const char *name, int dev, const unsigned char *rep, int len, unsigned expect)
{
    uint16_t w = 0xFFFF;
    int pl = hid_pad_report((uint8_t)dev, 0, rep, (uint16_t)len, &w);
    int ok = (pl >= 0 && w == expect);
    printf("%-34s -> jugador %d palabra %04X (esperado %04X) %s\n", name, pl, w, expect, ok ? "OK" : "FALLO");
    if (!ok) fails++;
}

int main(void)
{
    printf("mount dragonrise: jugador %d\n", hid_pad_mount(1, 0, dragonrise, sizeof dragonrise));
    printf("mount simple8   : jugador %d\n", hid_pad_mount(2, 0, simple8, sizeof simple8));
    printf("mount tercero   : %d (esperado -1: solo 2 mandos)\n", hid_pad_mount(3, 0, simple8, sizeof simple8));

    /* DragonRise: bytes 0-2 basura (01 7F 7F), X=byte3, Y=byte4, hat nibble byte5, botones desde bit 44 */
    unsigned char dr_idle[8]  = {0x01,0x7F,0x7F,0x7F,0x7F,0x0F,0x00,0x00};
    unsigned char dr_left[8]  = {0x01,0x7F,0x7F,0x00,0x7F,0x0F,0x00,0x00};
    unsigned char dr_down[8]  = {0x01,0x7F,0x7F,0x7F,0xFF,0x0F,0x00,0x00};
    unsigned char dr_hatur[8] = {0x01,0x7F,0x7F,0x7F,0x7F,0x01,0x00,0x00};   /* hat 1 = arriba-derecha */
    unsigned char dr_b1[8]    = {0x01,0x7F,0x7F,0x7F,0x7F,0x1F,0x00,0x00};   /* boton 1 = bit 44 = byte5 bit4 */
    unsigned char dr_b2_10[8] = {0x01,0x7F,0x7F,0x7F,0x7F,0x2F,0x20,0x00};   /* boton 2 (bit 45) + boton 10 (bit 53 = byte6 bit5) */
    check("dragonrise reposo", 1, dr_idle, 8, 0x0000);
    check("dragonrise izquierda (X=0)", 1, dr_left, 8, 0x0040);
    check("dragonrise abajo (Y=FF)", 1, dr_down, 8, 0x0020);
    check("dragonrise hat arriba-derecha", 1, dr_hatur, 8, 0x0090);
    check("dragonrise boton 1 -> A", 1, dr_b1, 8, 0x0100);
    check("dragonrise boton 2 -> B, 10 -> START", 1, dr_b2_10, 8, 0x0009);

    unsigned char s_idle[3] = {0x80,0x80,0x00};
    unsigned char s_ul[3]   = {0x00,0x00,0x00};
    unsigned char s_b1_7[3] = {0x80,0x80,0x41};                                /* botones 1 y 7 -> A + SEL */
    unsigned char s_right[3]= {0xFF,0x80,0x00};
    check("simple8 reposo", 2, s_idle, 3, 0x0000);
    check("simple8 arriba-izquierda", 2, s_ul, 3, 0x0050);
    check("simple8 botones 1 y 7", 2, s_b1_7, 3, 0x0104);
    check("simple8 derecha", 2, s_right, 3, 0x0080);

    printf("umount dragonrise: %d\n", hid_pad_umount(1, 0));
    printf("mount ds4like: jugador %d\n", hid_pad_mount(4, 0, ds4like, sizeof ds4like));
    unsigned char d_idle[10]  = {0x01, 0x80,0x80,0x80,0x80, 0x08, 0x00,0x00, 0x00,0x00};   /* hat 8 = ninguno */
    unsigned char d_hatdn[10] = {0x01, 0x80,0x80,0x80,0x80, 0x04, 0x00,0x00, 0x00,0x00};   /* hat 4 = abajo */
    unsigned char d_b1[10]    = {0x01, 0x80,0x80,0x80,0x80, 0x18, 0x00,0x00, 0x00,0x00};   /* boton 1 = bit 4 del byte 5 */
    unsigned char d_b9[10]    = {0x01, 0x80,0x80,0x80,0x80, 0x08, 0x10,0x00, 0x00,0x00};   /* boton 9 -> SEL */
    unsigned char d_badid[10] = {0x02, 0x00,0x00,0x00,0x00, 0x00, 0x00,0x00, 0x00,0x00};
    check("ds4like reposo", 4, d_idle, 10, 0x0000);
    check("ds4like hat abajo", 4, d_hatdn, 10, 0x0020);
    check("ds4like boton 1 -> A", 4, d_b1, 10, 0x0100);
    check("ds4like boton 9 -> SEL", 4, d_b9, 10, 0x0004);
    { uint16_t w; int pl = hid_pad_report(4, 0, d_badid, 10, &w);
      printf("%-34s -> %d %s\n", "ds4like report id ajeno", pl, pl < 0 ? "OK" : "FALLO"); if (pl >= 0) fails++; }

    printf("umount simple8: %d\n", hid_pad_umount(2, 0));
    printf("mount signed4: jugador %d\n", hid_pad_mount(5, 0, signed4, sizeof signed4));
    unsigned char g_idle[3] = {0x00,0x00,0x00};
    unsigned char g_ul[3]   = {0x81,0x90,0x00};        /* -127, -112 */
    unsigned char g_dr[3]   = {0x60,0x7F,0x00};        /* +96, +127 */
    unsigned char g_b4[3]   = {0x00,0x00,0x08};        /* boton 4 -> Y */
    check("signed4 reposo", 5, g_idle, 3, 0x0000);
    check("signed4 arriba-izquierda", 5, g_ul, 3, 0x0050);
    check("signed4 abajo-derecha", 5, g_dr, 3, 0x00A0);
    check("signed4 boton 4 -> Y", 5, g_b4, 3, 0x0002);

    printf(fails ? "\n%d FALLOS\n" : "\nTODO OK\n", fails);
    return fails ? 1 : 0;
}
